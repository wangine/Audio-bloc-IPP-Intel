#pragma once
#include "AudioQueues.h"
#include <resample.h>
#include <cmath>
#include <type_traits>
namespace entropy::live {
// Preparation-worker owner, never the WASAPI event owner. Output-driven WDL:
// only call ResampleOut with the EXACT requested input count. A short input is
// not flushed/zero-extended to conceal starvation. History survives every block.
class WdlClockAsrc final {
public:
 bool prepare(unsigned channels,unsigned maximumFrames) {
  static_assert(std::is_same_v<WDL_ResampleSample,double>);
  static_assert(std::is_same_v<WDL_SincFilterSample,double>);
  if(!channels||channels>16||!maximumFrames||maximumFrames>4096)return false;
  channels_=channels;maximum_=maximumFrames;
  resampler_.SetMode(true,0,true,128,1024);resampler_.SetFeedMode(false);
  resampler_.SetRates(192000.0,192000.0);
  // Includes worst supported near-unity ratio and startup/history guard.
  // Fixed filter bank is generated by WDL here, before any device Start.
  resampler_.Prealloc(int(channels),int(maximumFrames+512),int(maximumFrames+512));
  resampler_.Reset();sourcePosition_=0;lastBegin_=0;ready_=true;return true;
 }
 bool process(AudioQueue& queue,double* out,unsigned frames,double ratio) noexcept {
  if(!ready_||!out||!frames||frames>maximum_||queue.channels()!=channels_||!std::isfinite(ratio)||ratio<0.999||ratio>1.001)return false;
  resampler_.SetRates(192000.0*ratio,192000.0);
  WDL_ResampleSample* input=nullptr;
  const int requested=resampler_.ResamplePrepare(int(frames),int(channels_),&input);
  if(requested<0||unsigned(requested)>maximum_+512||!input){ready_=false;return false;}
  if(queue.readable()<unsigned(requested))return false;
  if(!queue.popInterleaved(input,unsigned(requested))){ready_=false;return false;}
  const int produced=resampler_.ResampleOut(out,requested,int(frames),int(channels_));
  if(produced!=int(frames)){ready_=false;return false;}
  lastBegin_=sourcePosition_;sourcePosition_+=double(frames)*ratio;return true;
 }
 bool healthy() const noexcept {return ready_;}
 double beginPosition() const noexcept {return lastBegin_;}
 double endPosition() const noexcept {return sourcePosition_;}
private:
 WDL_Resampler resampler_;unsigned channels_=0,maximum_=0;bool ready_=false;
 double sourcePosition_=0,lastBegin_=0;
};
}
